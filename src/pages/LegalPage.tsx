export default function LegalPage() {
  const location = useLocation();
  const path = location.pathname;

  let content = '';
  let title = '';

  if (path === '/privacy') {
    content = privacyContent;
    title = 'Privacy Policy';
  } else if (path === '/terms') {
    content = termsContent;
    title = 'Terms of Service';
  } else if (path === '/eula') {
    content = eulaContent;
    title = 'End User License Agreement';
  }

  // Simple markdown parser for the legal documents
  const renderMarkdown = (text: string) => {
    return text.split('\n').map((line, index) => {
      if (line.startsWith('# ')) {
        return <h1 key={index} className="text-4xl font-bold mb-6 mt-8">{line.replace('# ', '')}</h1>;
      } else if (line.startsWith('## ')) {
        return <h2 key={index} className="text-2xl font-bold mb-4 mt-8 text-white">{line.replace('## ', '')}</h2>;
      } else if (line.startsWith('### ')) {
        return <h3 key={index} className="text-xl font-bold mb-3 mt-6 text-white/90">{line.replace('### ', '')}</h3>;
      } else if (line.startsWith('- ')) {
        return <li key={index} className="ml-6 mb-2 list-disc text-text-secondary">{line.replace('- ', '').replace(/\*\*(.*?)\*\*/g, '<strong class="text-white">$1</strong>')}</li>;
      } else if (line.trim() === '') {
        return <br key={index} />;
      } else {
        // Handle bold text
        const parts = line.split(/(\*\*.*?\*\*)/g);
        return (
          <p key={index} className="mb-4 text-text-secondary leading-relaxed">
            {parts.map((part, i) => {
              if (part.startsWith('**') && part.endsWith('**')) {
                return <strong key={i} className="text-white">{part.slice(2, -2)}</strong>;
              }
              return part;
            })}
          </p>
        );
      }
    });
  };

  return (
    <div className="min-h-[80vh] pt-40 pb-20 px-6 max-w-4xl mx-auto relative z-20">
      <div className="glass-card p-8 md:p-12 border-white/5 bg-bg-secondary/30">
        <div className="prose prose-invert max-w-none">
          {renderMarkdown(content)}
        </div>
      </div>
    </div>
  );
}
